import os
# Подключаем получение режима работы из настроек запуска.
from rag.requests.controller import get
# Подключаем готовый сценарий поиска и ответа.
def main():
# Описываем пользовательскую точку входа программы.
 mode = os.getenv("RAG_MODE", "demo").strip().lower()
 # По умолчанию выбираем явно помеченную демонстрацию.
 print("Режим:", mode)
 # До запроса показываем, будет ли реальная генерация ответа.
 query = input("Вопрос: ")
 # Читаем один вопрос с клавиатуры как строку.
 answer = get(query, top_k=2, mode=mode)
 # Передаем вопрос контроллеру и запрашиваем до двух чанков.
 print("Ответ:")
 # Печатаем подпись перед полученным результатом.
 print(answer)
 # Показываем текст ответа или помеченный результат демонстрации.
if __name__ == "__main__":
# Проверяем, запущен ли main.py напрямую.
 main()
 # Запускаем сценарий только при явном запуске этого файла.