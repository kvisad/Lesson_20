import re
# Подключаем замену фрагментов по регулярному выражению.
def clean_content(content):
# Принимаем исходный текст и возвращаем очищенную строку.
 pattern = r"[^а-яА-ЯёЁ0-9.,!?\-\s]"
 # Указываем символы, которые удаляем из русской учебной базы.
 step_1 = re.sub(pattern, "", content)
 # Удаляем запрещенные символы, например проценты и решетки.
 return re.sub(r"\s+", " ", step_1).strip()
 # Сжимаем пробелы и переносы, затем убираем пробелы по краям.