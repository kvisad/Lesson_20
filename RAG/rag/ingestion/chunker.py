def get_chunks(content):
# Описываем простой разделитель текста по точке и пробелу.
 chunks = []
 # Готовим пустой список непустых фрагментов.

 for piece in content.split(". "):
 # Последовательно берем части текста между разделителями.
  piece = piece.strip()
 # Убираем пробелы по краям текущей части.
  if piece:
 # Добавляем только непустые строки.
   chunks.append(piece)
 # Сохраняем текущий фрагмент в конец списка.
 return chunks
 # Возвращаем список после обработки всех частей.
