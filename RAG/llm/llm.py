import os
# Подключаем чтение настроек из окружения текущего процесса.
from RAG.llm.promt_builder import build_prompt
# Подключаем построение запроса из вопроса и найденного текста.
def get_ai_response(query, chunks, mode="demo"):
# Принимаем вопрос, результаты поиска и явный режим работы.
 if not chunks:
 # Проверяем, есть ли текст, на который можно опереться.
  return "В базе нет ответа."
 # При пустом списке завершаем функцию без обращения к сервису.
 if mode == "demo":
 # Выбираем режим проверки цепочки без генеративной модели.
  return "[ДЕМО без генерации]\n" + chunks[0][0]
 # Показываем первый найденный текст с обязательной пометкой.
 if mode != "gemini":
 # Проверяем, не допущена ли опечатка в названии режима.
  raise ValueError("Режим должен быть demo или gemini")
 # Сообщаем об ошибке настройки вместо скрытого переключения.
 key = os.getenv("GEMINI_API_KEY", "").strip()
 # Читаем личный ключ; не записываем и не печатаем его в коде.
 if not key:
 # Проверяем, задан ли ключ именно для этого запуска.

  raise ValueError("Не задан GEMINI_API_KEY")
 # Останавливаем запрос с понятным сообщением.
 from google import genai
 # Подключаем новый SDK только когда действительно нужен Gemini.
 name = os.getenv("GEMINI_MODEL", "gemini-3.8-flash")
 # Берем имя модели из настройки или учебное значение по умолчанию.
 prompt = build_prompt(query, chunks)
 # Собираем вопрос, правила ответа и найденный контекст в одну строку.
 with genai.Client(api_key=key) as client:
 # Открываем клиент API и закроем его после завершения блока.
  response = client.models.generate_content(
 # Начинаем реальный сетевой запрос на генерацию текста.
   model=name,
 # Передаем имя генеративной модели, а не модели embeddings.
   contents=prompt,
 # Отправляем подготовленный текст вопроса и контекста.
 )
 # Получаем объект ответа после завершения вызова сервиса.
 answer = response.text
 # Извлекаем текст из ответа API.
 if not answer or not answer.strip():
 # Проверяем, что сервис вернул непустой текстовый ответ.
  raise RuntimeError("Gemini не вернул текстовый ответ")
 # Сообщаем об отсутствии текста вместо печати None.
 return answer.strip()
 # Возвращаем готовый ответ без внешних пробелов.
