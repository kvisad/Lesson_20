from RAG.llm.llm import get_ai_response
# Подключаем обработчик с явным выбором режима.
chunks = [("Заказы отправляются по предоплате", 0.81)]
# Используем учебный результат поиска с условной оценкой.
answer = get_ai_response("Как оплатить заказ?", chunks, mode="demo")
# Запрашиваем проверку связки без сетевого обращения к LLM.
print(answer)
# Видим пометку ДЕМО и первый текст, а не сгенерированную формулировку.
