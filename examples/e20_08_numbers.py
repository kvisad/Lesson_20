import numpy as np
# Подключаем массивы для маленького проверяемого числового примера.
from sklearn.metrics.pairwise import cosine_similarity
# Подключаем ту же операцию, что используется для поиска.
query = [[1.0, 0.0]]
# Готовим таблицу с одним учебным вектором вопроса.
vectors = [[0.0, 1.0], [1.0, 0.0], [0.8, 0.6]]
# Задаем три вектора с заранее понятными направлениями.
scores = cosine_similarity(query, vectors)[0]
# Берем всю строку из трех оценок, а не одно число.
indices = np.argsort(scores)[::-1][:2]
# Выбираем индексы двух наибольших оценок в убывающем порядке.
print(scores)
# Получаем оценки в исходном порядке документов.
print(indices)
# Получаем позиции лучших документов, а не сами оценки.
